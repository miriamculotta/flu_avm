class TarotCard {
  final String name;
  final String meaning;
  final String meaningUp;
  final String meaningRev;
  final String image;
  final bool reversed;

  TarotCard({
    required this.name,
    required this.meaning,
    required this.meaningUp,
    required this.meaningRev,
    required this.image,
    required this.reversed,
  });
}
